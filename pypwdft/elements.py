"""Element symbols and atomic numbers."""

# Element symbols ordered by atomic number; SYMBOLS[Z - 1] is element Z.
SYMBOLS = (
    "H", "He", "Li", "Be", "B", "C", "N", "O", "F", "Ne",
    "Na", "Mg", "Al", "Si", "P", "S", "Cl", "Ar", "K", "Ca",
    "Sc", "Ti", "V", "Cr", "Mn", "Fe", "Co", "Ni", "Cu", "Zn",
    "Ga", "Ge", "As", "Se", "Br", "Kr", "Rb", "Sr", "Y", "Zr",
    "Nb", "Mo", "Tc", "Ru", "Rh", "Pd", "Ag", "Cd", "In", "Sn",
    "Sb", "Te", "I", "Xe", "Cs", "Ba", "La", "Ce", "Pr", "Nd",
    "Pm", "Sm", "Eu", "Gd", "Tb", "Dy", "Ho", "Er", "Tm", "Yb",
    "Lu", "Hf", "Ta", "W", "Re", "Os", "Ir", "Pt", "Au", "Hg",
    "Tl", "Pb", "Bi", "Po", "At", "Rn", "Fr", "Ra", "Ac", "Th",
    "Pa", "U", "Np", "Pu", "Am", "Cm", "Bk", "Cf", "Es", "Fm",
    "Md", "No", "Lr", "Rf", "Db", "Sg", "Bh", "Hs", "Mt", "Ds",
    "Rg", "Cn", "Nh", "Fl", "Mc", "Lv", "Ts", "Og",
)

_ATOMIC_NUMBERS = {symbol: z for z, symbol in enumerate(SYMBOLS, start=1)}


def atomic_number(symbol):
    """Return the atomic number of an element symbol (case-insensitive)."""
    try:
        return _ATOMIC_NUMBERS[str(symbol).strip().capitalize()]
    except KeyError:
        raise ValueError(f"unknown element symbol: {symbol!r}") from None


def symbol(atomic_number):
    """Return the element symbol of an atomic number."""
    if atomic_number != int(atomic_number) or not 1 <= atomic_number <= len(SYMBOLS):
        raise ValueError(f"unknown atomic number: {atomic_number!r}")
    return SYMBOLS[int(atomic_number) - 1]
